/**
 * Writes src/icons.ts, the wixzel-ui/icons entry: every Phosphor icon,
 * already duotone, built on Phosphor's context-free SSR icons so Server
 * Components can render them. Runs before build and typecheck, so a Phosphor
 * upgrade brings its new icons along. The output is not committed.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { pathToFileURL } from "node:url";

const require = createRequire(import.meta.url);
const pkgDir = dirname(require.resolve("@phosphor-icons/react/package.json"));
const { version } = JSON.parse(readFileSync(join(pkgDir, "package.json"), "utf8")) as { version: string };
const ssr: Record<string, unknown> = await import(pathToFileURL(join(pkgDir, "dist/ssr/index.es.js")).href);

// Phosphor exports most icons twice (Gear and GearIcon, the same component).
// Wrap each component once and alias the other name to it.
const byIcon = new Map<unknown, string[]>();
for (const name of Object.keys(ssr).sort()) {
  if (name === "SSRBase") continue;
  byIcon.set(ssr[name], [...(byIcon.get(ssr[name]) ?? []), name]);
}
const icons = [...byIcon.values()].map((names) => {
  const main = names.find((n) => n.endsWith("Icon")) ?? names[0]!;
  return { main, aliases: names.filter((n) => n !== main) };
});

const lines = [
  `// Generated by scripts/icons.ts from @phosphor-icons/react ${version}. Do not edit.`,
  "",
  "/**",
  " * wixzel-ui/icons: Phosphor, drawn duotone, safe in Server Components.",
  " * Use it anywhere, client or server: import { Gear } from \"wixzel-ui/icons\".",
  " * Each icon is exported under both of Phosphor's names (Gear and GearIcon).",
  " */",
  'import * as P from "@phosphor-icons/react/dist/ssr";',
  'import { duotone } from "./lib/duotone";',
  "",
  'export type { Icon, IconProps, IconWeight } from "@phosphor-icons/react";',
  "",
  ...icons.map(({ main }) => `export const ${main} = /* @__PURE__ */ duotone(P.${main});`),
  "",
  `export { ${icons.flatMap(({ main, aliases }) => aliases.map((a) => `${main} as ${a}`)).join(", ")} };`,
  "",
];

writeFileSync(new URL("../src/icons.ts", import.meta.url), lines.join("\n"));
console.log(`icons: ${icons.length} icons`);
