#!/usr/bin/env node
/**
 * Prints the CSS for a product of your own, from one seed colour:
 *
 *   npx wixzel-ui --seed "#E4572E" > app/brand.css
 *
 * Import that file after wixzel-ui/styles.css. Every component, in both
 * themes, takes the colour; every text pair still passes WCAG AA.
 */
import { colorVariables, deriveProduct, type ProductSpec } from "./tokens.ts";

const args = process.argv.slice(2);
const flag = (name: string) => {
  const i = args.indexOf(`--${name}`);
  return i === -1 ? undefined : args[i + 1];
};

const seed = flag("seed");
if (!seed || !/^#?[0-9a-f]{6}$/i.test(seed) || args.includes("--help")) {
  console.error(`Usage: wixzel-ui --seed "#RRGGBB" [--tint 0.45] [--hue 0-360] [--font "Inter, sans-serif"] [--selector ":root"]

  --seed      your brand colour (required)
  --tint      how strongly the hue washes the page, 0 is grey (default 0.45)
  --hue       tint with this hue instead of the seed's, for a black or grey seed
  --font      a CSS font-family list to use instead of Manrope
  --selector  where the variables apply (default :root, so the whole page)`);
  process.exit(seed ? 0 : 1);
}

const spec: ProductSpec = { seed: seed.startsWith("#") ? seed : `#${seed}` };
if (flag("tint") !== undefined) spec.tint = Number(flag("tint"));
if (flag("hue") !== undefined) spec.hue = Number(flag("hue"));

const vars = Object.entries(colorVariables(deriveProduct(spec))).map(([k, v]) => `  ${k}: ${v};`);
const font = flag("font");
if (font) vars.push(`  --wx-font-sans: ${font};`);

// Doubled so it wins over the library's own :root, whichever file loads first.
const selector = flag("selector") ?? ":root:root";
console.log(`/* Generated by wixzel-ui from ${spec.seed}. */\n${selector} {\n${vars.join("\n")}\n}`);
