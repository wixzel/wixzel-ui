if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(out, "utf8");
  } catch {}
  if (current !== dart) {
    console.error("tokens: packages/flutter/lib/src/tokens.g.dart is stale. Run pnpm --filter @wixzel/tokens build.");
    process.exit(1);
  }
  console.log("tokens: Dart tokens are up to date");
} else {
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, dart);
  console.log("tokens: wrote packages/flutter/lib/src/tokens.g.dart");
}
